const r=require("express").Router();
const c=require("../controllers/authController");
const{protect,adminOnly}=require("../middleware/authMiddleware");
r.post("/register",c.register);
r.post("/login",c.login);
r.post("/change-password",protect,c.changeTemporaryPassword);
r.get("/me",protect,c.me);
r.put("/profile",protect,c.updateProfile);
r.post("/password",protect,c.changePassword);
r.post("/logout-all",protect,c.logoutAll);
r.patch("/preferences",protect,c.updatePreferences);
r.get("/admin",protect,adminOnly,(req,res)=>res.json({success:true,user:req.user}));
r.get("/admin/users",protect,adminOnly,c.adminUsers);
r.get("/admin/password-assistance/search",protect,adminOnly,c.adminPasswordSearch);
r.post("/admin/password-assistance/reset",protect,adminOnly,c.adminTemporaryPassword);
module.exports=r;
